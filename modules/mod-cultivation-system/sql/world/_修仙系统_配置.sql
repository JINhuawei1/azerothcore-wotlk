-- 修仙境界配置表
DROP TABLE IF EXISTS `_修仙境界配置`;
CREATE TABLE `_修仙境界配置` (
  `境界等级` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '境界等级(1-100)',
  `境界名称` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT '' COMMENT '境界名称',
  `大境界` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '大境界(1-10)',
  `小境界` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '小境界(1-10)',
  `属性加成百分比` float NOT NULL DEFAULT 0 COMMENT '当前等级的属性加成百分比',
  `升级需求ID` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '需求模板ID',
  `是否需要渡劫` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '0不需要 1需要渡劫才能进入下一大境界',
  `渡劫需求ID` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '渡劫消耗的需求模板ID',
  `渡劫Boss入口` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '渡劫Boss的creature_template entry',
  PRIMARY KEY (`境界等级`) USING BTREE
) ENGINE = MyISAM CHARACTER SET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = '修仙境界配置表' ROW_FORMAT = DYNAMIC;

-- 修仙技能配置表
DROP TABLE IF EXISTS `_修仙技能配置`;
CREATE TABLE `_修仙技能配置` (
  `技能ID` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '技能ID',
  `技能名称` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT '' COMMENT '技能名称',
  `解锁境界等级` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '解锁所需的境界等级',
  `法术ID` int UNSIGNED NOT NULL DEFAULT 0 COMMENT 'spell_id，0表示暂未实现',
  `技能类型` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '1主动 2被动 3辅助',
  `技能描述` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT '' COMMENT '技能效果描述',
  PRIMARY KEY (`技能ID`) USING BTREE
) ENGINE = MyISAM CHARACTER SET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = '修仙技能配置表' ROW_FORMAT = DYNAMIC;

