-- =========================================================
-- 待鉴定物品标记表孤立数据清理脚本
-- =========================================================
-- 问题描述：
--   玩家从幻境生物拾取物品后，系统会写入待鉴定标记
--   但如果玩家没有手动鉴定就把物品删除/出售/交易，标记不会被清理
--   导致表数据无限膨胀（已累积450万条记录）
--
-- 解决方案：
--   1. 运行此脚本一次性清理所有孤立数据
--   2. 代码已修复，添加了定期清理机制（每30分钟自动清理）
--
-- 注意：此脚本执行时间可能较长（取决于数据量），建议在低峰期执行
-- =========================================================

-- 第1步：统计当前待鉴定标记表的数据量
SELECT '清理前待鉴定物品标记表数据量:' AS '状态', COUNT(*) AS '记录数' FROM `待鉴定物品标记`;

-- 第2步：统计孤立数据量（物品已不存在的标记）
SELECT '孤立数据量（物品已删除）:' AS '状态', COUNT(*) AS '记录数'
FROM `待鉴定物品标记` p
LEFT JOIN `item_instance` i ON p.`物品GUID` = i.`guid`
WHERE i.`guid` IS NULL;

-- 第3步：删除孤立数据
-- 使用分批删除避免长时间锁表，每次删除10万条
-- 如果数据量非常大，可能需要多次执行此脚本

-- 分批删除，避免锁表时间过长
DELETE p FROM `待鉴定物品标记` p
LEFT JOIN `item_instance` i ON p.`物品GUID` = i.`guid`
WHERE i.`guid` IS NULL
LIMIT 100000;

-- 第4步：统计清理后的数据量
SELECT '清理后待鉴定物品标记表数据量:' AS '状态', COUNT(*) AS '记录数' FROM `待鉴定物品标记`;

