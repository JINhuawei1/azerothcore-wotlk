-- 挑战幻境自制 Boss 1001-2000 阶十倍加强。
-- 覆盖神符/回血、切割/裂锋、魔次、称号、转身五套守卫。
-- 使用确定性公式写入，避免重复导入时继续叠乘。

UPDATE `_属性调整_生物` a
JOIN (
  SELECT '神符守卫' AS `系统名`, 400000 AS `基数`
  UNION ALL SELECT '裂锋守卫', 410000
  UNION ALL SELECT '魔次守卫', 420000
  UNION ALL SELECT '称号守卫', 430000
  UNION ALL SELECT '转身守卫', 440000
) s ON a.`生物id` BETWEEN s.`基数` + 1001 AND s.`基数` + 2000
SET
  a.`攻击间隔` = 100,
  a.`血量值` = 0,
  a.`血量百分比` = ROUND(100 + 900 * POW((a.`生物id` - s.`基数`) / 101.0, 1.35), 2) * 10,
  a.`护甲值` = 0,
  a.`护甲百分比` = (100 + (a.`生物id` - s.`基数`) * 2.5) * 10,
  a.`抗性值` = 0,
  a.`抗性百分比` = (100 + (a.`生物id` - s.`基数`) * 2) * 10,
  a.`物理攻击最小值` = FLOOR((2000000000 + ((a.`生物id` - s.`基数`) - 101) * 100000000) * 0.5) * 10,
  a.`物理攻击最大值` = (2000000000 + ((a.`生物id` - s.`基数`) - 101) * 100000000) * 10,
  a.`魔法攻击最小值` = a.`魔法攻击最小值` * 10,
  a.`魔法攻击最大值` = a.`魔法攻击最大值` * 10,
  a.`DOT攻击最小值` = a.`DOT攻击最小值` * 10,
  a.`DOT攻击最大值` = a.`DOT攻击最大值` * 10,
  a.`治疗最小值` = a.`治疗最小值` * 10,
  a.`治疗最大值` = a.`治疗最大值` * 10,
  a.`真实伤害值` = (2000000000 + ((a.`生物id` - s.`基数`) - 101) * 100000000) * 10,
  a.`被攻击掉血上限` = a.`被攻击掉血上限` * 10,
  a.`物理攻击切割伤害值` = a.`物理攻击切割伤害值` * 10,
  a.`魔法攻击切割伤害值` = a.`魔法攻击切割伤害值` * 10,
  a.`DOT攻击切割伤害值` = a.`DOT攻击切割伤害值` * 10,
  a.`血条数量` = CAST((a.`生物id` - s.`基数`) * 300 AS CHAR)
WHERE a.`生物id` BETWEEN 401001 AND 402000
   OR a.`生物id` BETWEEN 411001 AND 412000
   OR a.`生物id` BETWEEN 421001 AND 422000
   OR a.`生物id` BETWEEN 431001 AND 432000
   OR a.`生物id` BETWEEN 441001 AND 442000;
