-- 说明：此表定义了物品回收的全局规则和配置
-- 注意：此表主要用于预定义回收规则，当前系统主要使用玩家个人配置
-- 玩家个人配置表位于角色数据库中：物品_回收玩家配置

DROP TABLE IF EXISTS `_物品回收_模板`;
CREATE TABLE `_物品回收_模板`  (
  `注释` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NULL DEFAULT NULL COMMENT '配置说明注释',
  `id` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '唯一标识ID',
  `组` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '回收组别，用于按组回收命令 .回收 回收 [组号]',
  `优先级` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '回收优先级，数字越小优先级越高',
  `物品id` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '特定物品ID，0表示通用规则',
  `回收需求` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '需求模板ID，0表示无需求，支持任意模板ID，对应需求_模板表',
  `回收奖励` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '奖励模板ID，0表示按商店价格给奖励或摧毁，支持任意模板ID，对应奖励_模板表',
  `回收类型` int UNSIGNED NOT NULL DEFAULT 1 COMMENT '物品类型：1=装备 2=消耗品 3=任务物品 4=垃圾 5=宝石 6=附魔材料',
  `最小等级` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '物品最小等级要求',
  `最大等级` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '物品最大等级要求，0表示无限制',
  `品质要求` int NOT NULL DEFAULT 0 COMMENT '物品品质要求：-1=所有品质 0=灰色 1=白色 2=绿色 3=蓝色 4=紫色 5=橙色 6=红色',
  `过滤物品` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT '' COMMENT '过滤物品ID列表，逗号分隔，如 6948,25,35,99,100',
  `启用状态` tinyint(1) NOT NULL DEFAULT 1 COMMENT '是否启用此回收规则',
  PRIMARY KEY (`id`) USING BTREE,
  INDEX `idx_group` (`组`) USING BTREE COMMENT '按组查询索引',
  INDEX `idx_type` (`回收类型`) USING BTREE COMMENT '按类型查询索引'
) ENGINE = MyISAM AUTO_INCREMENT = 1 CHARACTER SET = utf8mb4 COLLATE = utf8mb4_general_ci
COMMENT = '物品回收全局配置表 - 定义回收规则和预设配置' ROW_FORMAT = FIXED;

